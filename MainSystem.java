    private void updateTotal() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) UnitTable.getModel();
        double GrandTotal = 0;
        for (int i = 0; i < model.getRowCount(); i++ ) {
            GrandTotal += (Double) model.getValueAt(i, 3);
        }
        jLabel2.setText("Total: ₱" + String.format("%.2f", GrandTotal) );
    }
    
    private void populateProductList(){
        javax.swing.DefaultListModel<String> listModel = new javax.swing.DefaultListModel<>();
        Information[] inventory = service.getInventory();
        int count = service.getInventoryCount();
        
        for (int i = 0; i < count; i++) {
            listModel.addElement(inventory[i].getProductName());
        }
        jList1.setModel(listModel);
    }
    
