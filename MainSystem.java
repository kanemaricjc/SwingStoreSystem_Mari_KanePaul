    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
    String selectedItem = jList1.getSelectedValue();
    int quantity = (Integer) jSpinner1.getValue();
    Information[] inventory = service.getInventory();
    int count = service.getInventoryCount();
    
    if (selectedItem == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a product from the list!");
            return; 
        }
    
    for (int i = 0; i < count; i++) {
        if (inventory[i].getProductName().equals(selectedItem)) {
            double price = inventory[i].getPrice();
            double subtotal = price * quantity;

            // 1. Add to the Cart Table (UnitTable)
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) UnitTable.getModel();
            model.addRow(new Object[]{selectedItem, price, quantity, subtotal});

            // 2. Update the Total Label
            updateTotal();
            break;
        }
    }
    
    jSpinner1.setValue(1);    
    jList1.clearSelection();
            
    }//GEN-LAST:event_jButton1ActionPerformed

    private void CheckoutButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CheckoutButtonActionPerformed
    
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) UnitTable.getModel();
    
    if (model.getRowCount() == 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Way sulod bai.");
        return;
    }
    
    for (int i = 0; i < model.getRowCount(); i++) {
        String itemName = (String) model.getValueAt(i,0);
        double price = (double) model.getValueAt(i,1);
        int qtySold = (Integer) model.getValueAt(i,2);
        service.reduceStock(itemName, qtySold);
        
        Information saleRecord = new Information(itemName, price, qtySold);
        service.addTransaction(saleRecord);
    }
    
    javax.swing.JOptionPane.showMessageDialog(this, "Checkout Successful!");
    model.setRowCount(0);
    updateTotal();
    
    }//GEN-LAST:event_CheckoutButtonActionPerformed

